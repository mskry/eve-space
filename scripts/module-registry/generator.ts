function renderApiRoutes(compiled: CompiledPlatformModules) {
  const manifests = readCompiledPlatformModules(compiled)
  const reviewerContributions = installedReviewerContributionDescriptors(manifests)
  const routes = manifests.flatMap((manifest, moduleIndex) =>
    manifest.server.routes.map((route, routeIndex) => ({
      manifest,
      route,
      binding: `module${moduleIndex}Route${routeIndex}`,
      reviewerContributionIndex: reviewerContributions.findIndex(
        (contribution) =>
          contribution.moduleId === manifest.id && contribution.routeId === route.id,
      ),
    })),
  )
  const imports = renderServerImports(
    routes.map(({ manifest, route, binding }) => ({
      packageName: manifest.server.package,
      exportName: route.exportName,
      localName: `${binding}Factory`,
    })),
  )
  const hasReviewerContributions = routes.some(
    ({ reviewerContributionIndex }) => reviewerContributionIndex >= 0,
  )
  const hasLegacyRoutes = routes.some(
    ({ reviewerContributionIndex }) => reviewerContributionIndex < 0,
  )
  const compositionImports = [
    ...(hasReviewerContributions ? ['composePlatformReviewerContributionRoute'] : []),
    ...(hasLegacyRoutes ? ['platformModuleRouteComposers'] : []),
  ]
  const capabilityImports = [
    ...(routes.some(
      ({ route, reviewerContributionIndex }) =>
        reviewerContributionIndex < 0 && (route.target === undefined || route.target === 'caller'),
    )
      ? ['createPlatformModuleRouteCapabilities']
      : []),
    ...(hasReviewerContributions ? ['createPlatformReviewerContributionRouteCapabilities'] : []),
    ...(routes.some(
      ({ route, reviewerContributionIndex }) =>
        reviewerContributionIndex < 0 && route.target !== undefined && route.target !== 'caller',
    )
      ? ['createPlatformReviewerContributionRouteCapabilities']
      : []),
  ]
  const platformImports = routes.length
    ? [
        `import { ${compositionImports.join(', ')} } from '../../platform/module-route-composition.js'`,
        `import { ${capabilityImports.join(', ')} } from '../../platform/module-route-capabilities.js'`,
        ...(hasReviewerContributions
          ? [
              "import { installedReviewerContributions } from './installed-reviewer-contributions.js'",
            ]
          : []),
      ].join('\n') + '\n'
    : ''
  const factories = routes.map(({ manifest, route, binding, reviewerContributionIndex }) => {
    let capabilities: string
    if (reviewerContributionIndex >= 0)
      capabilities = `createPlatformReviewerContributionRouteCapabilities(installedReviewerContributions[${reviewerContributionIndex}]!, ${JSON.stringify(route.coreDataProducts ?? [])} as const)`
    else if (route.target !== undefined && route.target !== 'caller')
      capabilities = `createPlatformReviewerContributionRouteCapabilities({ moduleId: ${quote(manifest.id)} }, ${JSON.stringify(route.coreDataProducts ?? [])} as const)`
    else
      capabilities = `createPlatformModuleRouteCapabilities(${quote(manifest.id)}, ${quote(route.id)}, ${JSON.stringify(route.coreDataProducts ?? [])} as const)`
    return `const ${binding} = ${binding}Factory(${capabilities})\n`
  })
  const chain = routes.map(({ manifest, route, binding, reviewerContributionIndex }) => {
    const composer =
      route.target !== undefined && route.target !== 'caller' ? route.target : route.authorization
    const section = route.sectionId ? `, sectionId: ${quote(route.sectionId)}` : ''
    const additionalPermissions = route.additionalRequiredPermissions
      ? `, additionalRequiredPermissions: ${JSON.stringify(route.additionalRequiredPermissions)} as const`
      : ''
    const target = route.target ? `, target: ${quote(route.target)}` : ''
    const exposure = route.exposure ? `, exposure: ${quote(route.exposure)}` : ''
    const reviewerEvidence = route.reviewerEvidenceResourceId
      ? `, reviewerEvidence: { routeId: ${quote(route.id)}, resourceId: ${quote(route.reviewerEvidenceResourceId)}, operationId: ${quote(route.persistenceOperations[0]!.operationId)} }`
      : ''
    const sectionDescriptor = manifest.sections?.find(({ id }) => id === route.sectionId)
    const sectionResourceIds =
      sectionDescriptor?.kind === 'workspace'
        ? manifest.server.resources.map(({ id }) => id)
        : manifest.server.resources
            .filter(({ sectionId }) => sectionId === route.sectionId)
            .map(({ id }) => id)
    const reviewerResourceIds =
      reviewerContributionIndex < 0
        ? ''
        : `, reviewerResourceIds: ${JSON.stringify(sectionResourceIds)} as const`
    const organizationCommands = route.organizationCommands
      ? `, organizationCommands: ${JSON.stringify(route.organizationCommands)} as const`
      : ''
    const contributionRoute =
      reviewerContributionIndex >= 0
        ? `, routeId: ${quote(route.id)}, namespace: ${quote(route.namespace)}`
        : ''
    const organization = `{ publisherPackage: ${quote(manifest.release.publisherPackage)}, moduleId: ${quote(manifest.id)}${contributionRoute}, audience: ${quote(route.audience)}, requiredPermission: ${quote(route.requiredPermission)}${additionalPermissions}${section}${target}${exposure}${reviewerEvidence}${reviewerResourceIds}${organizationCommands} }`
    if (reviewerContributionIndex >= 0)
      return `\n  .route(\n    ${quote(route.namespace)},\n    composePlatformReviewerContributionRoute(\n      installedReviewerContributions[${reviewerContributionIndex}]!,\n      ${organization},\n      ${binding},\n    ),\n  )`
    return `\n  .route(\n    ${quote(route.namespace)},\n    platformModuleRouteComposers[${quote(composer)}](\n      ${quote(manifest.id)},\n      { publisherPackage: ${quote(manifest.release.publisherPackage)}, moduleId: ${quote(manifest.id)}, audience: ${quote(route.audience)}, requiredPermission: ${quote(route.requiredPermission)}${additionalPermissions}${section}${target}${exposure}${reviewerEvidence}${organizationCommands} },\n      ${binding},\n    ),\n  )`
  })
  const composition = routes.length ? `${platformImports}${imports}\n${factories.join('')}\n` : '\n'
  return `${generatedHeader}import { Hono } from 'hono'\n${composition}export const installedModuleRoutes = new Hono()${chain.join('')}\n`
}

function renderActivityProviders(compiled: CompiledPlatformModules) {
  const manifests = readCompiledPlatformModules(compiled)
  const providers = manifests.flatMap((manifest, moduleIndex) =>
    manifest.server.activityProviders.map((provider, providerIndex) => ({
      manifest,
      provider,
      binding: `module${moduleIndex}ActivityProvider${providerIndex}`,
    })),
  )
  const imports = renderServerImports(
    providers.map(({ manifest, provider, binding }) => ({
      packageName: manifest.server.package,
      exportName: provider.exportName,
      localName: `${binding}Factory`,
    })),
  )
  const platformImport = providers.length
    ? "import { createPlatformModuleActivityProviderCapabilities } from '../../platform/module-activity-provider-capabilities.js'\n"
    : ''
  const descriptors: PlatformInstalledActivityProviderDescriptor[] = providers.map(
    ({ manifest, provider }) => ({
      publisherPackage: manifest.release.publisherPackage,
      moduleId: manifest.id,
      providerId: provider.id,
      sectionId: provider.sectionId,
      coreDataProducts: provider.coreDataProducts ?? [],
      audience: provider.audience,
      requiredPermission: provider.requiredPermission,
      freshness: provider.freshness,
      pageIds: manifest.nuxt.pages.map(({ id }) => id),
      persistenceOperations: provider.persistenceOperations,
      invoke: undefined as never,
    }),
  )
  const rendered = descriptors.length
    ? `[${descriptors
        .map((descriptor, index) => {
          const binding = providers[index]!.binding
          const sectionId = descriptor.sectionId
            ? ` sectionId: ${quote(descriptor.sectionId)},`
            : ''
          return `\n  { publisherPackage: ${quote(descriptor.publisherPackage)}, moduleId: ${quote(descriptor.moduleId)}, providerId: ${quote(descriptor.providerId)},${sectionId} coreDataProducts: ${JSON.stringify(descriptor.coreDataProducts)} as const, audience: ${quote(descriptor.audience)}, requiredPermission: ${quote(descriptor.requiredPermission)}, freshness: { staleAfterSeconds: ${descriptor.freshness.staleAfterSeconds} }, pageIds: [${descriptor.pageIds.map(quote).join(', ')}], persistenceOperations: ${JSON.stringify(descriptor.persistenceOperations)} as const, invoke: (context) => ${binding}Factory(createPlatformModuleActivityProviderCapabilities(${quote(descriptor.moduleId)}, ${quote(descriptor.providerId)}, context, ${JSON.stringify(descriptor.coreDataProducts)} as const, ${descriptor.sectionId ? quote(descriptor.sectionId) : 'undefined'}))(context) },`
        })
        .join('')}\n]`
    : '[]'
  return `${generatedHeader}import type { PlatformInstalledActivityProviderDescriptor } from '@eve-space/platform-module-contract/activity'\n${platformImport}${imports}\nexport const installedModuleActivityProviders =\n  ${rendered} as const satisfies readonly PlatformInstalledActivityProviderDescriptor[]\n`
}

function renderWorkerResources(compiled: CompiledPlatformModules) {
  const manifests = readCompiledPlatformModules(compiled)
  const resources = manifests.flatMap((manifest, moduleIndex) =>
    manifest.server.resources.map((resource, resourceIndex) => ({
      manifest,
      resource,
      binding: `module${moduleIndex}Resource${resourceIndex}`,
    })),
  )
  const imports = renderServerImports(
    resources.map(({ manifest, resource, binding }) => ({
      packageName: manifest.server.package,
      exportName: resource.exportName,
      localName: binding,
    })),
  )
  const descriptors = resources.map(({ manifest, resource, binding }) => {
    const coreDataProducts = JSON.stringify(resource.coreDataProducts ?? [])
    const capabilityKey = quote(`${manifest.id}/${resource.id}`)
    const batch = resource.batch
      ? ` batch: { mode: ${quote(resource.batch.mode)}, operationId: ${quote(resource.batch.operationId)} },`
      : ''
    const dependent = resource.dependentOperationIds?.length
      ? ` dependentOperationIds: ${JSON.stringify(resource.dependentOperationIds)},`
      : ''
    const sectionId = resource.sectionId ? ` sectionId: ${quote(resource.sectionId)},` : ''
    const scheduled = resource.scheduled === false ? ' scheduled: false,' : ''
    const protocolOperations = [
      ...new Set([resource.operationId, ...(resource.dependentOperationIds ?? [])]),
    ]
      .map(quote)
      .join(' | ')
    const contract = `PlatformResourceImplementationForContract<typeof ${binding}, ${quote(resource.operationId)}, PlatformEsiOperationProtocol<${protocolOperations}>, readonly ${coreDataProducts}, InstalledModuleResourceProjectionPersistence<${capabilityKey}>, InstalledModuleResourceMaterializationPersistence<${capabilityKey}>>`
    return `({ moduleId: ${quote(manifest.id)}, resourceId: ${quote(resource.id)}, operationId: ${quote(resource.operationId)},${sectionId} coreDataProducts: ${coreDataProducts} as const,${dependent}${batch}${scheduled} subjectKind: ${quote(resource.subjectKind)}, materializationIntervalSeconds: ${resource.materializationIntervalSeconds}, eligibility: { kind: ${quote(resource.eligibility.kind)} }, persistence: ${JSON.stringify(resource.persistence)} as const, implementation: ${binding} satisfies ${contract} } as const)`
  })
  const rendered = descriptors.length ? `[${descriptors.join(', ')}]` : '[]'
  const importedTypes = resources.length
    ? 'PlatformInstalledResourceDescriptor, PlatformResourceImplementationForContract'
    : 'PlatformInstalledResourceDescriptor'
  const hostTypes = resources.length
    ? "import type { PlatformEsiOperationProtocol } from '../../esi-gateway/catalog-interface.js'\nimport type { InstalledModuleResourceMaterializationPersistence, InstalledModuleResourceProjectionPersistence } from './installed-module-persistence.js'\n"
    : ''
  return `${generatedHeader}import type { ${importedTypes} } from '@eve-space/platform-module-contract/resources'\n${hostTypes}${imports}export const installedModuleResources =\n  ${rendered} as const satisfies readonly PlatformInstalledResourceDescriptor[]\n`
}

