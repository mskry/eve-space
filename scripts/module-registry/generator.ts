function renderNavigationEntry(entry: PlatformInstalledNavigation) {
  const sectionId = entry.sectionId ? `    sectionId: ${quote(entry.sectionId)},\n` : ''
  return `\n  {\n    moduleId: ${quote(entry.moduleId)},\n${sectionId}    id: ${quote(entry.id)},\n    label: ${quote(entry.label)},\n    description: ${quote(entry.description)},\n    to: ${quote(entry.to)},\n    icon: ${quote(entry.icon)},\n    audience: ${quote(entry.audience)},\n    placement: ${quote(entry.placement)},\n    order: ${entry.order},\n    pageName: ${quote(entry.pageName)},\n  },`
}

function compareNavigation(left: PlatformInstalledNavigation, right: PlatformInstalledNavigation) {
  return (
    left.order - right.order ||
    compareStable(left.moduleId, right.moduleId) ||
    compareStable(left.id, right.id)
  )
}

function compareRuntimeNavigation(
  left: PlatformNavigationDefault,
  right: PlatformNavigationDefault,
) {
  return (
    platformNavigationPlacements.indexOf(left.placement) -
      platformNavigationPlacements.indexOf(right.placement) ||
    left.order - right.order ||
    compareStable(left.ownerId, right.ownerId) ||
    compareStable(left.navigationId, right.navigationId)
  )
}

function renderServerImports(
  imports: readonly { packageName: string; exportName: string; localName: string }[],
) {
  const specifiersByPackage = new Map<string, string[]>()
  for (const { packageName, exportName, localName } of imports) {
    const specifiers = specifiersByPackage.get(packageName) ?? []
    specifiers.push(`${exportName} as ${localName}`)
    specifiersByPackage.set(packageName, specifiers)
  }
  return [...specifiersByPackage]
    .map(([packageName, specifiers]) => {
      if (specifiers.length === 1) return `import { ${specifiers[0]} } from ${quote(packageName)}\n`
      const renderedSpecifiers = specifiers.map((specifier) => `  ${specifier},`).join('\n')
      return `import {\n${renderedSpecifiers}\n} from ${quote(packageName)}\n`
    })
    .join('')
}

function quote(value: string) {
  const backslash = String.fromCodePoint(92)
  const escapedSingleQuote = String.raw`\'`
  const escapedNewline = String.raw`\n`
  const escaped = value
    .replaceAll(backslash, backslash.repeat(2))
    .replaceAll("'", escapedSingleQuote)
    .replaceAll('\n', escapedNewline)
  return "'" + escaped + "'"
}

function compareStable(left: string, right: string) {
  if (left < right) return -1
  if (left > right) return 1
  return 0
}

export function assertOutputPath(root: string, path: string) {
  const output = resolve(root, path)
  const relativeOutput = relative(root, output)
  if (
    relativeOutput.startsWith(`..${sep}`) ||
    relativeOutput === '..' ||
    dirname(output) === output
  )
    throw new Error(`Generated output escapes the repository: ${path}`)
  return output
}
