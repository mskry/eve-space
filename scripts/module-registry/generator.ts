function renderPersistenceOperations(
  compiled: CompiledPlatformModules,
  routines: readonly ReviewedPersistenceRoutine[],
) {
  const manifests = readCompiledPlatformModules(compiled)
  const operations = manifests.flatMap((manifest, moduleIndex) =>
    manifest.server.persistenceOperations.map((operation, operationIndex) => ({
      manifest,
      operation,
      binding: `module${moduleIndex}PersistenceOperation${operationIndex}`,
      routine: routines.find(
        ({ identity }) =>
          identity.moduleId === manifest.id && identity.operationId === operation.id,
      ),
    })),
  )
  for (const { manifest, operation, routine } of operations)
    if (!routine)
      throw new Error(
        `Missing reviewed persistence routine ${manifest.id}/${operation.id} during registry generation`,
      )
  if (routines.length !== operations.length)
    throw new Error('Reviewed persistence routine inventory differs from module declarations')

  const imports = renderServerImports(
    operations.map(({ manifest, operation, binding }) => ({
      packageName: manifest.server.package,
      exportName: operation.exportName,
      localName: binding,
    })),
  )
  const descriptors = operations.map(({ manifest, operation, binding, routine }) => {
    const grants = persistenceOperationGrants(manifest, operation.id)
    return `{ moduleId: ${quote(manifest.id)}, operationId: ${quote(operation.id)}, method: ${quote(operation.method)}, revision: ${operation.revision}, mode: ${quote(operation.mode)}, migration: ${quote(operation.migration)}, schemaName: ${quote(routine!.identity.schemaName)}, routineName: ${quote(routine!.identity.routineName)}, definitionFingerprint: ${quote(routine!.definitionFingerprint)}, definition: ${binding} satisfies PlatformPersistenceOperationDefinition<${quote(operation.id)}, ${quote(operation.method)}, ${operation.revision}, ${quote(operation.mode)}>, grants: ${JSON.stringify(grants)} }`
  })
  const contractFingerprint = createModulePersistenceContractFingerprint(
    operations.map(({ manifest, operation, routine }) => ({
      moduleId: manifest.id,
      operationId: operation.id,
      method: operation.method,
      revision: operation.revision,
      mode: operation.mode,
      migration: operation.migration,
      schemaName: routine!.identity.schemaName,
      routineName: routine!.identity.routineName,
      definitionFingerprint: routine!.definitionFingerprint,
      grants: persistenceOperationGrants(manifest, operation.id),
    })),
    manifests.map(({ id }) => id),
  )
  const list = operations.length ? `[\n  ${descriptors.join(',\n  ')},\n]` : '[]'
  const catalog = operations.length
    ? `{${operations
        .map(({ manifest, operation }, index) => {
          const identity = `${manifest.id}/${operation.id}`
          return `\n  ${quote(identity)}: installedModulePersistenceOperations[${index}]!,`
        })
        .join('')}\n}`
    : '{}'
  const factories = renderPersistenceCapabilityFactories(manifests, operations)
  const platformImports = operations.length
    ? `import {\n  bindPlatformPersistenceOperation,\n  type PlatformInstalledPersistenceOperationDescriptor,\n  type PlatformPersistenceOperationDefinition,\n  type PlatformPersistenceOperationInvoker,\n} from '@eve-space/platform-module-server'\n`
    : "import type { PlatformInstalledPersistenceOperationDescriptor, PlatformPersistenceOperationInvoker } from '@eve-space/platform-module-server'\n"
  return `${generatedHeader}${platformImports}${imports}\nexport const installedModulePersistenceOperations = ${list} as const satisfies readonly PlatformInstalledPersistenceOperationDescriptor[]\n\nexport const installedModulePersistenceContractFingerprint = ${quote(contractFingerprint)}\n\nexport const installedModulePersistenceOperationCatalog = ${catalog} as const\n${factories}`
}

function renderPersistenceCapabilityFactories(
  manifests: readonly PlatformModuleManifest[],
  operations: readonly {
    readonly manifest: PlatformModuleManifest
    readonly operation: PlatformModuleManifest['server']['persistenceOperations'][number]
  }[],
) {
  const operationIndex = new Map(
    operations.map(({ manifest, operation }, index) => [`${manifest.id}/${operation.id}`, index]),
  )
  const factories = manifests.flatMap((manifest, moduleIndex) => [
    ...manifest.server.routes.map((route, routeIndex) => ({
      name: `createModule${moduleIndex}Route${routeIndex}Persistence`,
      group: 'routes' as const,
      key: `${manifest.id}/${route.id}`,
      manifest,
      references: route.persistenceOperations,
    })),
    ...manifest.server.activityProviders.map((provider, providerIndex) => ({
      name: `createModule${moduleIndex}ActivityProvider${providerIndex}Persistence`,
      group: 'activityProviders' as const,
      key: `${manifest.id}/${provider.id}`,
      manifest,
      references: provider.persistenceOperations,
    })),
    ...manifest.server.resources.flatMap((resource, resourceIndex) => [
      {
        name: `createModule${moduleIndex}Resource${resourceIndex}ProjectionPersistence`,
        group: 'resourceProjections' as const,
        key: `${manifest.id}/${resource.id}`,
        manifest,
        references: resource.persistence.projection,
      },
      {
        name: `createModule${moduleIndex}Resource${resourceIndex}MaterializationPersistence`,
        group: 'resourceMaterializations' as const,
        key: `${manifest.id}/${resource.id}`,
        manifest,
        references: resource.persistence.materialization,
      },
    ]),
  ])
  const declarations = factories
    .map(({ name, manifest, references }) => {
      const methods = references.map(({ operationId }) => {
        const index = operationIndex.get(`${manifest.id}/${operationId}`)
        if (index === undefined)
          throw new Error(`Missing persistence binding ${manifest.id}/${operationId}`)
        const operation = manifest.server.persistenceOperations.find(
          ({ id }) => id === operationId,
        )!
        return `${quote(operation.method)}: bindPlatformPersistenceOperation(installedModulePersistenceOperations[${index}]!, invoke),`
      })
      const parameter = methods.length > 0 ? 'invoke' : '_invoke'
      const renderedMethods = methods.length ? `\n    ${methods.join('\n    ')}\n  ` : ''
      return `\nexport function ${name}(${parameter}: PlatformPersistenceOperationInvoker) {\n  return {${renderedMethods}}\n}\n`
    })
    .join('')
  const groups = [
    'routes',
    'activityProviders',
    'resourceProjections',
    'resourceMaterializations',
  ] as const
  const catalogs = groups
    .map((group) => {
      const entries = factories
        .filter((factory) => factory.group === group)
        .map(({ key, name }) => `\n    ${quote(key)}: ${name},`)
        .join('')
      return `\n  ${group}: {${entries}${entries ? '\n  ' : ''}},`
    })
    .join('')
  return `${declarations}\nexport const installedModulePersistenceCapabilityFactories = {${catalogs}\n} as const\n\nexport type InstalledModuleResourceProjectionPersistence<\n  Key extends keyof typeof installedModulePersistenceCapabilityFactories.resourceProjections,\n> = ReturnType<(typeof installedModulePersistenceCapabilityFactories.resourceProjections)[Key]>\n\nexport type InstalledModuleResourceMaterializationPersistence<\n  Key extends keyof typeof installedModulePersistenceCapabilityFactories.resourceMaterializations,\n> = ReturnType<(typeof installedModulePersistenceCapabilityFactories.resourceMaterializations)[Key]>\n`
}

